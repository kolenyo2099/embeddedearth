"""
Result Grid Component

Displays search results in an accessible grid layout
with heatmap overlays and download options.
"""


import streamlit as st
import numpy as np
from typing import List, Optional
from io import BytesIO
from PIL import Image

import sys
sys.path.insert(0, str(__file__).rsplit('/', 3)[0])
from config import ui_config
from xai.visualization import create_heatmap_overlay, generate_caption
from app.export_utils import generate_pdf_report, generate_kmz, generate_geojson, generate_zip_package

def render_result_grid(
    results: List[dict],
    show_heatmaps: bool = True,
    columns: int = None,
    key_prefix: str = "res"
):
    """
    Render search results in an accessible grid with export capabilities.
    """
    if not results:
        st.info("No results to display. Try a different query or expand your search area.")
        return
    
    columns = columns or ui_config.results_per_row

    # --- State Management for Selection ---
    # A signature of the current result set detects a new search; stale
    # selections/checkbox state from a previous search must not carry over
    # (the indices would silently point at different tiles).
    selection_key = f"{key_prefix}_selection"
    signature_key = f"{key_prefix}_results_signature"
    signature = (len(results), tuple(round(r.get('score', 0.0), 6) for r in results))

    if st.session_state.get(signature_key) != signature:
        st.session_state[signature_key] = signature
        st.session_state[selection_key] = set(range(len(results)))  # Default all selected
        stale_keys = [
            k for k in st.session_state
            if k.startswith(f"{key_prefix}_chk_") or k.startswith(f"{key_prefix}_export_")
        ]
        for k in stale_keys:
            st.session_state.pop(k, None)

    selected_indices = st.session_state[selection_key]
    
    # --- Header & Controls ---
    st.markdown("### 🎯 Search Results")
    
    control_col1, control_col2, control_col3 = st.columns([1.5, 1, 1])
    
    with control_col1:
        st.markdown(f"Found **{len(results)}** tiles. Selected: **{len(selected_indices)}**")
        
    with control_col2:
        # Selection Controls
        if st.button("Select All", key=f"{key_prefix}_sel_all"):
            # Update the main tracking set
            st.session_state[selection_key] = set(range(len(results)))
            # Force update of individual widget keys to reflect in UI
            for i in range(len(results)):
                st.session_state[f"{key_prefix}_chk_{i}"] = True
            st.rerun()
            
        if st.button("Deselect All", key=f"{key_prefix}_desel_all"):
            st.session_state[selection_key] = set()
            # Force update of individual widget keys to reflect in UI
            for i in range(len(results)):
                st.session_state[f"{key_prefix}_chk_{i}"] = False
            st.rerun()
            
    with control_col3:
        # Master heatmap toggle
        master_heatmap_key = f"{key_prefix}_master_heatmap"
        show_heatmaps = st.toggle(
            "🔥 Show Heatmaps", 
            value=st.session_state.get(master_heatmap_key, True), # Default True
            key=master_heatmap_key
        )
        
        # Heatmap Type Selector
        # Offer whichever alternative visualizations the results actually carry
        vis_options = ["Similarity Scan"]
        if results and 'dino_attention' in results[0]:
            vis_options.append("DINO Attention")
        if results and 'pca_map' in results[0]:
            vis_options.append("PCA Clusters")

        heatmap_mode = "Similarity"
        if len(vis_options) > 1:
             heatmap_mode = st.radio(
                 "Visualization Mode",
                 vis_options,
                 horizontal=True,
                 key=f"{key_prefix}_vis_mode"
             )
        
    # --- Export Menu ---
    with st.expander("📤 Export Options", expanded=False):
        st.caption("Select format to download the SELECTED results.")
        
        # Filter results based on selection
        export_subset = [results[i] for i in sorted(list(selected_indices))]
        
        if not export_subset:
            st.warning("⚠️ No results selected for export.")
        else:
            # Retrieve query from session state for reports
            current_query = st.session_state.get('current_query', "Unknown Query")

            # Generated bytes are stashed in session state so the download button
            # survives the rerun triggered by clicking it (or anything else).
            export_formats = [
                ("📄 PDF Report", "pdf",
                 lambda: bytes(generate_pdf_report(export_subset, current_query)),
                 "mission_report.pdf", "application/pdf"),
                ("🌍 Google Earth (KMZ)", "kmz",
                 lambda: generate_kmz(export_subset),
                 "results.kmz", "application/vnd.google-earth.kmz"),
                ("🗺️ GIS (GeoJSON)", "geojson",
                 lambda: generate_geojson(export_subset),
                 "results.geojson", "application/geo+json"),
                ("💻 Raw Data (ZIP)", "zip",
                 lambda: generate_zip_package(export_subset, current_query),
                 "raw_data.zip", "application/zip"),
            ]

            # Selection-specific cache key: changing the selection invalidates
            # previously generated downloads instead of serving stale bytes.
            selection_tag = hash(tuple(sorted(selected_indices)))

            export_cols = st.columns(len(export_formats))
            for (label, fmt, generate, file_name, mime), exp_col in zip(export_formats, export_cols):
                cache_key = f"{key_prefix}_export_{fmt}_{selection_tag}"
                with exp_col:
                    if st.button(label, key=f"{key_prefix}_gen_{fmt}"):
                        with st.spinner(f"Generating {fmt.upper()}..."):
                            st.session_state[cache_key] = generate()
                    if cache_key in st.session_state:
                        st.download_button(
                            f"⬇️ Download {fmt.upper()}",
                            data=st.session_state[cache_key],
                            file_name=file_name,
                            mime=mime,
                            key=f"{key_prefix}_dl_{fmt}"
                        )

    # Interpretation Guide
    with st.expander("ℹ️ How to interpret these results", expanded=False):
        st.markdown("...") # Kept brief for diff clarity, can stay properly
    
    # --- Grid Rendering ---
    # DOFA-CLIP cosine scores live around 0.1–0.3; DINOv3/CopernicusFM patch
    # similarities live around 0.5–0.9. Detect the scale from the result set
    # so the score color coding stays meaningful in every mode.
    max_score = max((r.get('score', 0.0) for r in results), default=0.0)
    high_scale = max_score > 0.45

    for row_start in range(0, len(results), columns):
        row_results = results[row_start:row_start + columns]
        cols = st.columns(columns)

        for idx, (col, result) in enumerate(zip(cols, row_results)):
            global_idx = row_start + idx

            with col:
                # Check if selected
                is_selected = global_idx in selected_indices
                
                # Render Selection Checkbox ABOVE the card content or as part of it
                # Native checkboxes inside columns work fine
                
                # Capture selection change
                new_selected = st.checkbox(
                    f"Select Result #{global_idx+1}", 
                    value=is_selected, 
                    key=f"{key_prefix}_chk_{global_idx}",
                    label_visibility="visible" 
                )
                
                # Update state immediately if changed (requires rerun usually, but st handles it)
                if new_selected != is_selected:
                    if new_selected:
                        selected_indices.add(global_idx)
                    else:
                        selected_indices.discard(global_idx)
                    # We might need to force rerun if we want the "Selected count" to update instantly
                    # For now rely on next interact
                
                _render_result_card(
                    result=result,
                    index=global_idx,
                    default_heatmap_on=show_heatmaps,
                    key_prefix=key_prefix,
                    is_selected=new_selected,
                    heatmap_mode=heatmap_mode,
                    high_scale=high_scale
                )


def _render_result_card(
    result: dict,
    index: int,
    default_heatmap_on: bool = False,
    key_prefix: str = "res",
    is_selected: bool = True,
    heatmap_mode: str = "Similarity",
    high_scale: bool = False
):
    """
    Render a single result card.
    """
    image = result.get('image')

    # Select overlay based on mode. PCA is a full RGB image (semantic clusters),
    # the others are (H, W) heatmaps blended over the tile.
    pca_image = None
    heatmap = None
    if "Attention" in heatmap_mode:
        heatmap = result.get('dino_attention')
    elif "PCA" in heatmap_mode:
        pca_image = result.get('pca_map')
    else:
        heatmap = result.get('heatmap')

    score = result.get('score', 0.0)
    bounds = result.get('bounds')

    if image is None: return

    # Ensure image is uint8
    if image.dtype != np.uint8:
        image = (np.clip(image, 0, 1) * 255).astype(np.uint8)

    # Highlight border if selected? (Streamlit styling hard, but maybe markdown text)
    if is_selected:
        st.markdown("✅ **Selected**")

    # Controls Row: Score
    c1, c2 = st.columns([1, 1])
    with c1:
        score_color = _get_score_color(score, high_scale)
        st.markdown(
            f'<div style="background-color: {score_color}; padding: 4px; border-radius: 4px; color: white;">{score:.1%}</div>',
            unsafe_allow_html=True
        )

    show_heatmap = default_heatmap_on
    with c2:
        if heatmap is not None or pca_image is not None:
            show_heatmap = st.toggle(
                "Heatmap",
                value=default_heatmap_on,
                key=f"{key_prefix}_heatmap_{index}"
            )

    # Apply overlay
    if show_heatmap and pca_image is not None:
        display_image = pca_image
    elif show_heatmap and heatmap is not None:
        display_image = create_heatmap_overlay(image, heatmap)
    else:
        display_image = image
    
    # Caption
    caption = generate_caption(score, bounds, index)
    
    st.image(display_image, caption=caption, use_column_width=True)
    
    # Actions (Maps + Single DL)
    c_act1, c_act2 = st.columns([1, 1])
    with c_act1:
        if bounds:
           # Maps link code...
           minx, miny, maxx, maxy = bounds
           center_lat = (miny + maxy) / 2
           center_lon = (minx + maxx) / 2
           maps_url = f"https://www.google.com/maps/search/?api=1&query={center_lat},{center_lon}"
           st.markdown(f'[📍 Map]({maps_url})')
           
    with c_act2:
        _download_result(image, index, key_prefix)


def _get_score_color(score: float, high_scale: bool = False) -> str:
    """
    Get color based on similarity score.

    Thresholds depend on the score scale: DOFA-CLIP cosine similarities are
    strong from ~0.15, while DINOv3/CopernicusFM similarities are strong
    from ~0.6.
    """
    good, ok = (0.75, 0.6) if high_scale else (0.25, 0.15)
    if score >= good: return "#16a34a"
    elif score >= ok: return "#ca8a04"
    else: return "#ea580c"


def _download_result(image: np.ndarray, index: int, key_prefix: str):
    """Create downloadable image."""
    img_pil = Image.fromarray(image)
    buffer = BytesIO()
    img_pil.save(buffer, format="PNG")
    buffer.seek(0)
    
    st.download_button(
        label="📥 Png",
        data=buffer,
        file_name=f"result_{index + 1}.png",
        mime="image/png",
        key=f"{key_prefix}_dl_btn_{index}"
    )

def render_no_results():
    """Display message when no results are found."""
    st.warning("No Matching Results found. Try adjusting filters.")

def render_loading_state():
    """Display loading state."""
    with st.spinner("🔍 Searching..."):
        return st.progress(0), st.empty()

def update_loading_progress(progress, status, current, total, message="Processing..."):
    pct = current / total if total > 0 else 0
    progress.progress(pct)
    status.text(f"{message} ({current}/{total})")
